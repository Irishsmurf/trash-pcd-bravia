#!/usr/bin/env python3
"""Generate ops/100000.bravia-web-profiles.sql for this trash-pcd fork.

Usage: python3 -I bravia/build_op.py > ops/100000.bravia-web-profiles.sql

The op runs after every upstream TRaSH op (Profilarr sorts ops by number). It copies TRaSH's
WEB-2160p / WEB-1080p *at apply time* (qualities, groups, languages, tags, every CF score),
then applies OVERRIDES. Upstream tier/group changes therefore flow into the BRAVIA profiles
on every merge. An override whose CF no longer exists upstream is skipped instead of failing.
"""

PROFILES = {
    # new profile name: TRaSH base profile
    "WEB-2160p (BRAVIA 3.0)": "WEB-2160p",
    "WEB-1080p (BRAVIA 3.0)": "WEB-1080p",
}

DESCRIPTION = ("TRaSH {base} tuned for Sony BRAVIA Google TV (Plex, direct play) -> eARC -> "
               "Marantz Cinema 70s, 3.0 speakers. Prefers WEB DV P5/P8 + DD+ Atmos. Blocks "
               "DV Profile 7, TrueHD, x265 HD and penalises multichannel AAC.")

NEW_REGEX = [
    ("Multichannel (5.1-7.1)", r"[^0-9][5-7][ .][0-1]\b",
     "5.x, 6.x or 7.x channel layout in the release title"),
]

NEW_CFS = [
    {
        "name": "DV FEL (Profile 7)",
        "description": "Dolby Vision from a Blu-ray / Remux / BR-DISK source. These carry the "
                       "Profile 7 dual-layer (FEL/MEL) stream that the Sony Android TV Plex app "
                       "can't play cleanly. WEB DV (Profile 5/8) is never matched.",
        "conditions": [
            # (name, type, negate, required, (kind, value))
            ("Dolby Vision", "release_title", 0, 1, ("regex", "Dolby Vision")),
            ("Bluray", "source", 0, 0, ("source", "bluray")),
            ("BR-DISK", "source", 0, 0, ("source", "bluray_raw")),
        ],
        "tests": [
            ("Movie.2023.2160p.UHD.BluRay.REMUX.DV.HDR.HEVC.TrueHD.7.1.Atmos-FraMeSToR", 1),
            ("Movie.2023.2160p.BluRay.DoVi.HDR10.x265.DTS-HD.MA.7.1-SWTYBLZ", 1),
            ("Movie.2023.2160p.AMZN.WEB-DL.DDP5.1.Atmos.DV.HDR10.H.265-FLUX", 0),
        ],
    },
    {
        "name": "AAC (Multichannel)",
        "description": "AAC 5.1 / 6.1 / 7.1. Android TV channel-maps multichannel AAC "
                       "badly when downmixing. 2.0 AAC is not matched.",
        "conditions": [
            ("AAC", "release_title", 0, 1, ("regex", "AAC")),
            ("Multichannel", "release_title", 0, 1, ("regex", "Multichannel (5.1-7.1)")),
            ("Not Basic Dolby Digital", "release_title", 1, 1, ("regex", "Not Basic Dolby Digital")),
            ("Not Dolby Digital Plus", "release_title", 1, 1, ("regex", "Not Dolby Digital Plus")),
            ("Not DTS", "release_title", 1, 1, ("regex", "Not DTS")),
            ("Not FLAC", "release_title", 1, 1, ("regex", "Not FLAC")),
            ("Not PCM", "release_title", 1, 1, ("regex", "Not PCM")),
            ("Not TrueHD/ATMOS", "release_title", 1, 1, ("regex", "Not TrueHD/ATMOS")),
        ],
        "tests": [
            ("Movie.2023.1080p.WEB-DL.AAC5.1.H.264-GROUP", 1),
            ("Show.S01E01.1080p.WEB-DL.AAC.7.1.H.264-GROUP", 1),
            ("Movie.2023.1080p.WEB-DL.AAC2.0.H.264-GROUP", 0),
            ("Movie.2023.1080p.WEB-DL.DDP5.1.H.264-GROUP", 0),
        ],
    },
]

# Score overrides, applied to both Radarr and Sonarr sides of both profiles.
OVERRIDES = {
    # Video / HDR
    "DV Boost": 1500,               # any WEB DV: Profile 5 and Profile 8
    "HDR10": 500,                   # TRaSH "HDR" catch-all; also adds to DV HDR10 (P8)
    "DV FEL (Profile 7)": -10000,   # custom, above
    "DV (Disk)": -10000,            # TRaSH: FraMeSToR P7 remuxes
    # Audio
    "DD+ ATMOS": 2000,
    "DTS": 500,                     # DTS core only (not DTS-HD MA / DTS:X)
    "TrueHD": -10000,
    "TrueHD ATMOS": -10000,
    "AAC (Multichannel)": -1500,    # custom, above
    # Junk / bad encodes
    "x265 (HD)": -10000,            # x265 at <=1080p (no effect on 2160p by design)
    "Retags": -10000,
    "Obfuscated": -10000,
    # Repacks
    "Repack/Proper": 10,
    "Repack2": 11,
    "Repack3": 12,
}


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    out = []
    w = out.append
    w("-- @operation: create")
    w("-- @entity: batch")
    w("-- @name: BRAVIA 3.0 WEB profiles (Sony Google TV / Plex direct play, Marantz eARC)")
    w("-- Generated by bravia/build_op.py. Edit that file, not this one.")
    w("")

    w("-- ---- Regular expressions")
    for name, pat, desc in NEW_REGEX:
        w(f"INSERT INTO regular_expressions (name, pattern, regex101_id, description) "
          f"VALUES ({q(name)}, {q(pat)}, NULL, {q(desc)});")
    w("")

    for cf in NEW_CFS:
        n = cf["name"]
        w(f"-- ---- Custom format: {n}")
        w(f"INSERT INTO custom_formats (name, description, include_in_rename) VALUES ({q(n)}, {q(cf['description'])}, 0);")
        w(f"INSERT INTO custom_format_tags (custom_format_name, tag_name) "
          f"SELECT {q(n)}, name FROM tags WHERE name = 'Miscellaneous';")
        for cname, ctype, neg, req, (kind, val) in cf["conditions"]:
            w(f"INSERT INTO custom_format_conditions (custom_format_name, name, type, arr_type, negate, required) "
              f"VALUES ({q(n)}, {q(cname)}, {q(ctype)}, 'all', {neg}, {req});")
            if kind == "regex":
                w(f"INSERT INTO condition_patterns (custom_format_name, condition_name, regular_expression_name) "
                  f"VALUES ({q(n)}, {q(cname)}, {q(val)});")
            elif kind == "source":
                w(f"INSERT INTO condition_sources (custom_format_name, condition_name, source) "
                  f"VALUES ({q(n)}, {q(cname)}, {q(val)});")
        for title, should in cf["tests"]:
            w(f"INSERT INTO custom_format_tests (custom_format_name, title, type, should_match) "
              f"VALUES ({q(n)}, {q(title)}, 'movie', {should});")
        w("")

    for new, base in PROFILES.items():
        N, B = q(new), q(base)
        w(f"-- ---- Quality profile: {new} (live copy of TRaSH '{base}' + overrides)")
        w(f"INSERT INTO quality_profiles (name, description, upgrades_allowed, minimum_custom_format_score, "
          f"upgrade_until_score, upgrade_score_increment)\n"
          f"  SELECT {N}, {q(DESCRIPTION.format(base=base))} || char(10) || char(10) || COALESCE(description, ''), "
          f"upgrades_allowed, minimum_custom_format_score, upgrade_until_score, upgrade_score_increment\n"
          f"  FROM quality_profiles WHERE name = {B};")
        w(f"INSERT INTO quality_profile_tags (quality_profile_name, tag_name)\n"
          f"  SELECT {N}, tag_name FROM quality_profile_tags WHERE quality_profile_name = {B};")
        w(f"INSERT INTO quality_profile_languages (quality_profile_name, language_name, type)\n"
          f"  SELECT {N}, language_name, type FROM quality_profile_languages WHERE quality_profile_name = {B};")
        w(f"INSERT INTO quality_groups (quality_profile_name, name)\n"
          f"  SELECT {N}, name FROM quality_groups WHERE quality_profile_name = {B} ORDER BY id;")
        w(f"INSERT INTO quality_group_members (quality_profile_name, quality_group_name, quality_name)\n"
          f"  SELECT {N}, quality_group_name, quality_name FROM quality_group_members WHERE quality_profile_name = {B};")
        w(f"INSERT INTO quality_profile_qualities (quality_profile_name, quality_name, quality_group_name, position, enabled, upgrade_until)\n"
          f"  SELECT {N}, quality_name, quality_group_name, position, enabled, upgrade_until\n"
          f"  FROM quality_profile_qualities WHERE quality_profile_name = {B} ORDER BY position;")
        w(f"INSERT INTO quality_profile_custom_formats (quality_profile_name, custom_format_name, arr_type, score)\n"
          f"  SELECT {N}, custom_format_name, arr_type, score FROM quality_profile_custom_formats WHERE quality_profile_name = {B};")
        w("-- overrides (skipped if the CF no longer exists upstream)")
        for cf, sc in OVERRIDES.items():
            for arr in ("radarr", "sonarr"):
                w(f"INSERT OR REPLACE INTO quality_profile_custom_formats (quality_profile_name, custom_format_name, arr_type, score) "
                  f"SELECT {N}, name, {q(arr)}, {sc} FROM custom_formats WHERE name = {q(cf)};")
        w("")

    print("\n".join(out))


if __name__ == "__main__":
    main()
